#!/usr/bin/env node
/* MIGRATION TOOL — one-shot, not a build dependency.
 *
 * Lifts the design-token layer (the `:root` custom-property blocks) out of a
 * Sass-compiled theme and writes it as a plain CSS token file. Token values are
 * *data*, not Sass logic: they are already authored as CSS custom properties,
 * `oklch(from ...)` and `color-mix()`. Porting them mechanically is exactly what
 * a real migration would do once, by hand or by script.
 *
 * The component CSS in poc/src/core is written from scratch and does NOT derive
 * from the Sass build.
 *
 * Usage: node poc/build/extract-tokens.mjs <compiled.css> <out.css> <layer>
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const [, , src, out, layer = "kendo.tokens"] = process.argv;

if (!src || !out) {
    console.error("usage: extract-tokens.mjs <compiled.css> <out.css> [layer]");
    process.exit(1);
}

const css = readFileSync(src, "utf8");

/* Collect every `:root { ... }` block, in source order, and merge them.
 * Later declarations win, matching the cascade of the original file.
 *
 * Split on `}` rather than using a single regex: consecutive `:root` blocks
 * share their delimiters, so a regex that has to consume the preceding `}`
 * silently skips every other block. */
const tokens = new Map();
let blocks = 0;

for (const chunk of css.split("}")) {
    const brace = chunk.indexOf("{");
    if (brace < 0) { continue; }

    const selector = chunk.slice(0, brace).trim().replace(/\s+/g, " ");
    const isRoot = selector
        .split(",")
        .some((s) => s.trim() === ":root");
    if (!isRoot) { continue; }

    blocks++;
    for (const decl of chunk.slice(brace + 1).split(";")) {
        const idx = decl.indexOf(":");
        if (idx < 0) { continue; }
        const prop = decl.slice(0, idx).trim();
        const value = decl.slice(idx + 1).trim();
        if (prop.startsWith("--")) { tokens.set(prop, value); }
    }
}

const body = [...tokens.entries()]
    .map(([p, v]) => `        ${p}: ${v};`)
    .join("\n");

const output = `/* Generated by poc/build/extract-tokens.mjs — design tokens only.
 * Source: ${src}
 * ${blocks} :root block(s) merged into ${tokens.size} custom properties. */

@layer ${layer} {
    :root {
${body}
    }
}
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, output);

console.log(`extracted ${tokens.size} tokens from ${blocks} :root blocks -> ${out}`);
